<!-- GSAP ScrollTrigger Logic for Horizontal Pin -->
<script src="https://cdnjs.cloudflare.com/ajax/libs/gsap/3.12.2/ScrollTrigger.min.js"></script>
<script>
    document.addEventListener("DOMContentLoaded", () => {
        gsap.registerPlugin(ScrollTrigger);

        const sections = gsap.utils.toArray(".service-slide");
        const wrapper = document.querySelector(".pin-panel-wrapper");

        // Horizontal Scroll Animation
        gsap.to(sections, {
            xPercent: -100 * (sections.length - 1),
            ease: "none",
            scrollTrigger: {
                trigger: "#horizontalSection",
                pin: true,
                scrub: 1,
                snap: 1 / (sections.length - 1),
                end: () => "+=" + document.querySelector(".pin-panel-wrapper").offsetWidth
            }
        });

        // Simple Stats Animation
        gsap.from(".stat-item", {
            scrollTrigger: {
                trigger: "#statsGrid",
                start: "top 90%",
            },
            y: 30,
            duration: 1,
            stagger: 0.15,
            ease: "power3.out"
        });
    });
</script>
